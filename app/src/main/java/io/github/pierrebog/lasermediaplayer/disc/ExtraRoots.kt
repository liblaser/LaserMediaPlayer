    /** Android 7.1.1 is the first to know ISRG Root X1. */
    private val needed = Build.VERSION.SDK_INT < Build.VERSION_CODES.N_MR1

    private val socketFactory: SSLSocketFactory? by lazy {
        runCatching {
            val system = trustManager(null)
            val extra = trustManager(KeyStore.getInstance(KeyStore.getDefaultType()).apply {
                load(null, null)
                val factory = CertificateFactory.getInstance("X.509")
                ROOTS.forEachIndexed { i, pem ->
                    setCertificateEntry("isrg$i",
                        factory.generateCertificate(ByteArrayInputStream(pem.toByteArray())))
                }
            })
            SSLContext.getInstance("TLS").apply {
                init(null, arrayOf(Either(system, extra)), null)
            }.socketFactory
        }.getOrNull()
    }

    /** Lets [connection] trust Let's Encrypt where the system does not. */
    fun apply(connection: HttpURLConnection) {
        if (!needed || connection !is HttpsURLConnection) return
        socketFactory?.let { connection.sslSocketFactory = it }
    }

    /** The default trust manager of [keyStore], the system's for null. */
    private fun trustManager(keyStore: KeyStore?): X509TrustManager =
        TrustManagerFactory.getInstance(TrustManagerFactory.getDefaultAlgorithm()).run {
            init(keyStore)
            trustManagers.filterIsInstance<X509TrustManager>().first()
        }

    /** The system's verdict, else the extra roots'. */
    private class Either(
        private val system: X509TrustManager,
        private val extra: X509TrustManager,
    ) : X509TrustManager {
        override fun checkClientTrusted(chain: Array<X509Certificate>, authType: String) =
            system.checkClientTrusted(chain, authType)

        override fun checkServerTrusted(chain: Array<X509Certificate>, authType: String) {
            try {
                system.checkServerTrusted(chain, authType)
            } catch (e: CertificateException) {
                try {
                    extra.checkServerTrusted(chain, authType)
                } catch (_: CertificateException) {
                    throw e
                }
            }
        }

        override fun getAcceptedIssuers(): Array<X509Certificate> =
            system.acceptedIssuers + extra.acceptedIssuers
    }
}
